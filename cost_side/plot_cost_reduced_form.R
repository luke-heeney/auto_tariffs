  "- Residualize both axes on differenced controls and year fixed effects.",
  paste0("- Split the sample at the median lagged imported-parts exposure: ", sprintf("%.4f", median_exposure), "."),
  "- Bin the residualized exchange-rate shock into eight quantile bins within each exposure group.",
  "",
  "## Output Files",
  "",
  "- `cost_reduced_form_binned.csv`",
  "- `cost_reduced_form_fx.png`"
)
writeLines(notes_lines, file.path(out_dir, "cost_reduced_form_notes.md"))

cat("Saved:\n")
cat(" -", file.path(out_dir, "cost_reduced_form_binned.csv"), "\n")
cat(" -", file.path(out_dir, "cost_reduced_form_fx.png"), "\n")
